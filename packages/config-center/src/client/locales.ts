export type TranslateValues = Record<string, string | number>

let runtimeT: ((key: Key, values?: TranslateValues) => string) | undefined

/** Bind the shell's translator; absent, `tt` follows the document language. */
export function setRuntimeTranslate(t: ((key: Key, values?: TranslateValues) => string) | undefined): void {
  runtimeT = t
}

function interpolate(dict: Record<string, string>, key: string, values?: TranslateValues): string {
  const template = dict[key] ?? key
  if (values === undefined) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match))
}

/** Translate a key (current language). */
export function tt(key: Key, values?: TranslateValues): string {
  if (runtimeT !== undefined) {
    try {
      const value = runtimeT(key, values)
      if (typeof value === 'string' && value !== '' && value !== key) return value
    } catch { /* document-language fallback */ }
  }
  const lang = typeof document !== 'undefined' ? document.documentElement.lang : 'zh'
  return interpolate(lang.toLowerCase().startsWith('en') ? en : zh, key, values)
}

/** Translate a key built at run time; unknown keys return `fallback`. */
export function ttOr(key: string, fallback: string, values?: TranslateValues): string {
  return key in zh ? tt(key as Key, values) : fallback
}

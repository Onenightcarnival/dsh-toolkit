export type TranslateValues = Record<string, string | number>

export function interpolate(dictionary: Record<string, string>, key: string, values?: TranslateValues): string {
  let text = dictionary[key] ?? key
  if (values !== undefined) for (const [name, value] of Object.entries(values)) text = text.replaceAll(`{${name}}`, String(value))
  return text
}

let runtimeT: ((key: RdbKey, values?: TranslateValues) => string) | undefined
export function setRuntimeTranslate(t: ((key: RdbKey, values?: TranslateValues) => string) | undefined): void { runtimeT = t }

function dictionary(): Record<string, string> {
  const lang = typeof document !== 'undefined' ? document.documentElement.lang : 'zh'
  return lang.toLowerCase().startsWith('en') ? en : zh
}

export function tt(key: RdbKey, values?: TranslateValues): string {
  if (runtimeT !== undefined) {
    try {
      const value = runtimeT(key, values)
      if (typeof value === 'string' && value !== '' && value !== key) return value
    } catch { /* fall through */ }
  }
  return interpolate(dictionary(), key, values)
}

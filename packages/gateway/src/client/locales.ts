type Values = Record<string, string | number>
let runtime: ((key: Key, values?: Values) => string) | undefined

export function setRuntimeTranslate(t: ((key: Key, values?: Values) => string) | undefined): void { runtime = t }

function interpolate(template: string, values?: Values): string {
  return values === undefined ? template : template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''))
}

export function tt(key: Key, values?: Values): string {
  if (runtime !== undefined) {
    try {
      const value = runtime(key, values)
      if (typeof value === 'string' && value !== '' && value !== key) return value
    } catch { /* document-language fallback */ }
  }
  const dict = typeof document !== 'undefined' && document.documentElement.lang.startsWith('en') ? en : zh
  return interpolate(dict[key], values)
}
